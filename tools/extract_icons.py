"""Extracts Gatefold's SVG icon symbols (theme/index.html) into source/icons.inc.

Usage: python tools/extract_icons.py <gatefold>/theme/index.html source/icons.inc
Each icon becomes a standalone white SVG; the app sets its size and tints it.
"""
import re, sys

html = open(sys.argv[1], encoding='utf-8').read()
WANT = ['play', 'pause', 'prev', 'next', 'shuffle', 'repeat', 'repeat1', 'order', 'vol', 'vol-x', 'disc', 'list',
        'grid', 'queue', 'search', 'gear', 'menu', 'sidebar', 'plus', 'music', 'folder', 'chev', 'more', 'mic',
        'back', 'heart', 'heart-f', 'pause-c', 'pip', 'canvas', 'image', 'x', 'sparkle', 'refresh', 'quote',
        'sliders', 'wave', 'info', 'check', 'download', 'tag', 'v-albums', 'v-covers', 'v-grid', 'v-list', 'sort-down',
        'sort-up', 'sun', 'moon']
out = ['// Generated by tools/extract_icons.py from Gatefold theme/index.html (MIT). Do not edit.', '#pragma once']
for name in WANT:
    m = re.search(r'<symbol id="i-%s" ([^>]*)>(.*?)</symbol>' % re.escape(name), html, re.S)
    if not m:
        sys.exit('missing icon ' + name)
    attrs, body = m.group(1), m.group(2)
    svg = '<svg xmlns="http://www.w3.org/2000/svg" width="%%d" height="%%d" %s>%s</svg>' % (attrs, body)
    svg = svg.replace('currentColor', '#ffffff')
    ident = 'ICON_' + name.upper().replace('-', '_')
    out.append('inline constexpr char %s[] = R"SVG(%s)SVG";' % (ident, svg))

# The brand mark: the "G" and its folded corner, drawn as two tinted layers.
g = re.search(r'class="bm-g" d="([^"]+)"', html).group(1)
fold = re.search(r'class="bm-fold"[^>]*d="([^"]+)"', html).group(1)
for ident, d in (('ICON_BRAND_G', g), ('ICON_BRAND_FOLD', fold)):
    out.append('inline constexpr char %s[] = R"SVG(<svg xmlns="http://www.w3.org/2000/svg" width="%%d" height="%%d" viewBox="0 0 100 100"><path d="%s" fill="#ffffff"/></svg>)SVG";' % (ident, d))
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(len(out) - 1, 'icons')
