/*
 * Songate · tools/brand/overlay_icons.cpp
 * The app's playlist icons (source/icons.inc, plicons.inc: every key a playlist can wear) rasterised for the overlay, which
 * cannot draw SVG: overlay/source/pl_symbols.hpp, an AlphaSymbol per key (symbol.hpp's format: one byte of alpha a pixel)
 * and a lookup by key. Drawn by SDL_image's SVG renderer, as the app draws them, so the overlay's marks are the same.
 *
 *   bash tools/brand/overlay_icons.sh   (builds this with the preview's SDL, runs it, writes the header)
 */
#include <SDL2/SDL.h>
#include <SDL2/SDL_image.h>

#include <cstdio>
#include <cstring>
#include <string>

#include "icons.inc"
#include "plicons.inc"

int main(int argc, char** argv) {
    if (argc < 2) { fprintf(stderr, "usage: overlay_icons <out.hpp> [size]\n"); return 2; }
    const int px = argc > 2 ? atoi(argv[2]) : 24;
    FILE* out = fopen(argv[1], "wb");
    if (!out) return 1;
    fprintf(out, "/* Generated by tools/brand/overlay_icons.cpp from source/icons.inc and plicons.inc. Do not edit.\n"
                 " * The app's playlist icons for the overlay (%d px, one byte of alpha a pixel, as symbol.hpp's). */\n"
                 "#pragma once\n#include <cstring>\n\n#include \"symbol.hpp\"\n\nnamespace plsym {\n", px);
    std::string table;
    int n = 0;
    for (const PlaylistIcon& ic : kPlaylistIcons) {
        std::string doc(strlen(ic.svg) + 32, '\0');
        doc.resize(size_t(snprintf(doc.data(), doc.size(), ic.svg, px, px)));
        SDL_Surface* s = IMG_LoadSVG_RW(SDL_RWFromConstMem(doc.data(), int(doc.size())));
        if (!s) { fprintf(stderr, "%s: %s\n", ic.key, IMG_GetError()); return 1; }
        SDL_Surface* r = SDL_ConvertSurfaceFormat(s, SDL_PIXELFORMAT_RGBA32, 0);
        SDL_FreeSurface(s);
        std::string id = ic.key;
        for (char& c : id) if (c == '-') c = '_';
        fprintf(out, "inline constexpr u8 %s_data[%d] = {", id.c_str(), r->w * r->h);
        for (int y = 0; y < r->h; y++) {
            fprintf(out, "\n    ");
            const Uint8* row = static_cast<const Uint8*>(r->pixels) + y * r->pitch;
            for (int x = 0; x < r->w; x++) fprintf(out, "%d,", row[x * 4 + 3]);
        }
        fprintf(out, "\n};\ninline constexpr AlphaSymbol %s(%d, %d, %s_data);\n", id.c_str(), r->w, r->h, id.c_str());
        table += "        { \"" + std::string(ic.key) + "\", &" + id + " },\n";
        SDL_FreeSurface(r);
        n++;
    }
    fprintf(out, "\nstruct Entry { const char* key; const AlphaSymbol* sym; };\ninline constexpr Entry kAll[] = {\n%s};\n\n"
                 "/** The symbol of an icon key (bg-playlists.txt's \"!icons\"), the list's when it is unknown. */\n"
                 "inline const AlphaSymbol& of(const char* key) {\n"
                 "    for (const Entry& e : kAll) if (!strcmp(e.key, key)) return *e.sym;\n"
                 "    return list;\n}\n\n}  // namespace plsym\n", table.c_str());
    fclose(out);
    printf("%d icons at %d px\n", n, px);
    return 0;
}
