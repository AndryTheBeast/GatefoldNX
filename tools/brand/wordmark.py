"""Songate's wordmark: "Songate" in Fraunces Black (soft, wonky: tools/brand/Fraunces.ttf, SIL OFL, OFL.txt), drawn here once
and kept in the app as two alpha masks (source/wordmark.inc): the letters, and their blurred copy for the glow. The app
colours them itself (Gfx::wordmark: a gradient from the theme's accent, a shimmer, a sparkle), so one mask suits every theme.

    python tools/brand/wordmark.py          (Pillow; writes source/wordmark.inc)
"""
import os
from PIL import Image, ImageDraw, ImageFont, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'source', 'wordmark.inc')
TEXT, PX, SS = 'Songate', 22, 8          # 22 px on the 1280x720 screen, drawn 8x larger and brought down (crisp edges)
AXES = [36, 900, 100, 1]                 # opsz, wght, SOFT, WONK
GLOW_PAD, GLOW_BLUR = 10, 4.5

font = ImageFont.truetype(os.path.join(HERE, 'Fraunces.ttf'), PX * SS)
font.set_variation_by_axes(AXES)
pad = 4 * SS
l, t, r, b = font.getbbox(TEXT)
big = Image.new('L', (r - l + 2 * pad, b - t + 2 * pad), 0)
ImageDraw.Draw(big).text((pad - l, pad - t), TEXT, font=font, fill=255)
# where the letters stand: the middle between the capital's top and the baseline (what the app centres on the bar)
cap_top = font.getbbox('S')[1] - t + pad
baseline = font.getmetrics()[0] - t + pad
box = big.getbbox()
big = big.crop(box)
mid = ((cap_top + baseline) / 2 - box[1]) / SS
w, h = (big.width + SS - 1) // SS, (big.height + SS - 1) // SS
canvas = Image.new('L', (w * SS, h * SS), 0)
canvas.paste(big, (0, 0))
word = canvas.resize((w, h), Image.LANCZOS)

glow = Image.new('L', (w + 2 * GLOW_PAD, h + 2 * GLOW_PAD), 0)
glow.paste(word, (GLOW_PAD, GLOW_PAD))
glow = glow.filter(ImageFilter.GaussianBlur(GLOW_BLUR))
peak = max(glow.tobytes()) or 1
glow = glow.point(lambda a: min(255, round(a * 255 / peak)))

def arr(name, img):
    data = list(img.tobytes())
    rows = [', '.join(str(v) for v in data[i:i + 32]) for i in range(0, len(data), 32)]
    return f'inline constexpr unsigned char {name}[] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'

src = ('// Generated by tools/brand/wordmark.py: "Songate" in Fraunces Black (SIL OFL, tools/brand/OFL.txt). Do not edit.\n'
       '#pragma once\n'
       f'inline constexpr int kWordW = {w}, kWordH = {h};\n'
       f'inline constexpr float kWordMid = {mid:.2f}f;   // the letters\' middle (capital top to baseline), from the top\n'
       f'inline constexpr int kWordGlowPad = {GLOW_PAD};\n'
       + arr('kWord', word) + arr('kWordGlow', glow))
open(OUT, 'w', newline='\r\n').write(src)
# Four times as many pixels for the PC's big windows (Gfx::init takes it where the app is built with GF_WINDOWED)
word4 = canvas.resize((w * 4, h * 4), Image.LANCZOS)
open(os.path.join(os.path.dirname(OUT), 'wordmark4.inc'), 'w', newline='\r\n').write(
    '// Generated by tools/brand/wordmark.py: the wordmark at four times the size. Do not edit.\n#pragma once\n' + arr('kWord4', word4))
print(f'{w}x{h}, middle {mid:.2f}; {OUT}')
